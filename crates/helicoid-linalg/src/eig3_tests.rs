/// Whether every entry of `a` is a number of `S`.
fn fits<S: Lane>(a: &M) -> bool {
    let r = round::<S>(a);
    (0..9).all(|i| r[i / 3][i % 3].to_bits() == a[i / 3][i % 3].to_bits())
}

fn strata<S: Lane>() {
    for &(name, e, lam, vec) in MP {
        let a = matrix(e);
        if !fits::<S>(&a) {
            continue;
        }
        note(name, check::<S>(name, &a, &Truth { lam, vec }));
    }
}

