/// A seeded stream of numbers in `[-1, 1]` (splitmix64).
fn lcg(seed: u64) -> impl FnMut() -> f64 {
    let mut state = seed;
    move || {
        state = state.wrapping_add(0x9E37_79B9_7F4A_7C15);
        let z = (state ^ (state >> 30)).wrapping_mul(0xBF58_476D_1CE4_E5B9);
        let z = (z ^ (z >> 27)).wrapping_mul(0x94D0_49BB_1331_11EB);
        (z ^ (z >> 31)) as f64 / u64::MAX as f64 * 2.0 - 1.0
    }
}

/// The matrices of the fixture, the special cases and 100 seeded random ones.
fn pool() -> Vec<M> {
    let mut rows: Vec<M> = MP.iter().map(|r| matrix(r.1)).collect();
    let (inf, nan) = (f64::INFINITY, f64::NAN);
    rows.extend([
        diag([0.0; 3]),
        diag([2.0; 3]),
        diag([1.0, 100.0, 100.0]),
        diag([0.0, 0.0, 9.0]),
        matrix([1.0, 1.0, 1.0, 1e-20, 1e-20, 1e-20]),
        matrix([nan, 1.0, 1.0, 0.0, 0.0, 0.0]),
        matrix([1.0, 1.0, 1.0, inf, 0.0, 0.0]),
        matrix([1e-310; 6]),
        matrix([1e300; 6]),
        matrix([1e-30, 2e-30, 3e-30, 1e-31, 0.0, 1e-31]),
    ]);
    let mut next = lcg(1);
    rows.extend(
        (0..100).map(|_| matrix([(); 6].map(|()| next() * 2f64.powi((next() * 8.0) as i32)))),
    );
    rows
}

/// Equal to the bit, except that a `NaN` matches any `NaN` (its sign and payload are unspecified).
fn same(x: f64, y: f64) -> bool {
    x.to_bits() == y.to_bits() || x.is_nan() && y.is_nan()
}

/// The value path of `Dual` is the plain value path: eigenvalues and eigenvectors to the bit.
fn value_path<S: Real<Mask = bool>, T: Real<Mask = bool>>(
    conv: fn(f64) -> S,
    lift: fn(S, usize) -> T,
) {
    for a in pool() {
        let x = Mat3::from_rows(a.map(|r| Vector(r.map(conv))));
        let y = Mat3::from_rows(
            [0, 1, 2].map(|i| Vector([0, 1, 2].map(|j| lift(x.get(i, j), 3 * i + j)))),
        );
        let ((pl, pv), (dl, dv)) = (eig3(&x), eig3(&y));
        for (p, d) in pl.0.iter().zip(dl.0) {
            assert!(same(p.value_f64(), d.value_f64()), "{a:?}");
        }
        for i in 0..9 {
            assert!(
                same(
                    pv.get(i % 3, i / 3).value_f64(),
                    dv.get(i % 3, i / 3).value_f64()
                ),
                "{a:?}"
            );
        }
    }
}

#[test]
