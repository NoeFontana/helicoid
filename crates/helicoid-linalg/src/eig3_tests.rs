/// The frame, the order and the residual bound of `eig3` at `S` on any matrix; truth-free. The
/// frame is orthonormal for every input, and a non-finite entry leaves no finite eigenvalue.
fn frame_of_any<S: Lane>(a: &M) -> Result<(), TestCaseError> {
    let (a, u) = (round::<S>(a), unit::<S>());
    let (l, v) = run::<S>(&a);
    let (orth, det) = frame(&v);
    prop_assert!(
        orth <= 16.0 * u && det <= 16.0 * u,
        "{a:?}: {orth:e} {det:e}"
    );
    if a.iter().flatten().any(|x| !x.is_finite()) {
        prop_assert!(l.iter().all(|x| !x.is_finite()), "{a:?}: {l:?}");
        return Ok(());
    }
    prop_assert!(
        l.iter().all(|x| x.is_finite()) && l[0] <= l[1] && l[1] <= l[2],
        "{a:?}: {l:?}"
    );
    let an = l[0].abs().max(l[2].abs());
    if an > 0.0 && l[2] - l[1] >= 4.0 * u.sqrt() * an {
        let c = 1.0 + (an / (l[1] - l[0]).min(l[2] - l[1])).min(1.0 / u.sqrt());
        for (k, lk) in l.iter().enumerate() {
            let r = residual(&a, *lk, col(&v, k));
            prop_assert!(r <= (K * c + SLACK) * u * an, "{a:?}: res {r:e} l {l:?}");
        }
    }
    Ok(())
}

proptest! {
    #![proptest_config(cfg())]

    /// Any matrix, the degenerate and the non-finite ones included (a third of the entries are ties,
    /// zeros or non-finite): the frame is orthonormal with `det = +1`; for a non-finite matrix no
    /// eigenvalue is finite; and for a finite matrix the eigenvalues ascend and are finite, and the
    /// residual meets the recorded bound wherever the computed top gap is at least `4 sqrt(u) |A|`.
    #[test]
    fn any_matrix_gives_an_orthonormal_frame(e in prop::array::uniform6(entry())) {
        frame_of_any::<f64>(&matrix(e))?;
        frame_of_any::<f32>(&matrix(e))?;
    }
}

fn diag(d: V3) -> M {
    array::from_fn(|i| array::from_fn(|j| if i == j { d[i] } else { 0.0 }))
}

/// omnisac's cases (`eig3::tests`): the axes of a diagonal matrix, the eigen equation and the unit
/// length on its `7, 3, 2, 1, .5, .25` matrix, an indefinite diagonal, a rank-2 matrix and a
/// negative definite one. Its rejections are now answers: a multiple of the identity (also zero
/// and a negative trace) is the identity and near isotropy is a decomposition; non-finite entries
/// are `a_non_finite_entry_has_no_eigenvalues`.
fn omnisac_cases<S: Lane>() {
    let u = unit::<S>();
    let near = |x: f64, y: f64| (x - y).abs() <= 64.0 * u * y.abs().max(1.0);
    for (d, want, axes) in [
        ([3.0, 5.0, 1.0], [1.0, 3.0, 5.0], [2, 0, 1]),
        ([2.0, -3.0, 5.0], [-3.0, 2.0, 5.0], [1, 0, 2]),
        ([-1.0, -2.0, -3.0], [-3.0, -2.0, -1.0], [2, 1, 0]),
    ] {
        let (l, v) = run::<S>(&diag(d));
        for k in 0..3 {
            assert!(
                near(l[k], want[k]) && near(v[axes[k]][k].abs(), 1.0),
                "{d:?}: {l:?} {v:?}"
            );
        }
    }
    let m = matrix([7.0, 3.0, 2.0, 1.0, 0.5, 0.25]);
    let (l, v) = run::<S>(&m);
    assert!(l[0] < l[1] && l[1] < l[2]);
    for k in 0..3 {
        assert!((norm(col(&v, k)) - 1.0).abs() <= 8.0 * u);
        assert!(residual(&m, l[k], col(&v, k)) <= 64.0 * u * l[2]);
    }
    for c in [0.0, 3.0, -0.375, -1.0, 1e-3] {
        let (l, v) = run::<S>(&diag([c; 3]));
        let id = diag([1.0; 3]);
        let is_id = (0..9).all(|i| v[i / 3][i % 3].abs().to_bits() == id[i / 3][i % 3].to_bits());
        assert!(l.iter().all(|x| near(*x, c)) && is_id, "{c}: {l:?} {v:?}");
    }
    let (l, v) = run::<S>(&matrix([1.0, 1.0, 1.0, 1e-20, 1e-20, 1e-20]));
    assert!(l.iter().all(|x| near(*x, 1.0)) && frame(&v).0 <= 16.0 * u);
}

