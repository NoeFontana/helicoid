/// The rotation of the unnormalised quaternion `(w, x, y, z)`.
fn rotation([w, x, y, z]: [f64; 4]) -> M {
    let k = 2.0 / (w * w + x * x + y * y + z * z);
    let (xx, yy, zz) = (k * x * x, k * y * y, k * z * z);
    let (xy, xz, yz) = (k * x * y, k * x * z, k * y * z);
    let (wx, wy, wz) = (k * w * x, k * w * y, k * w * z);
    [
        [1.0 - yy - zz, xy - wz, xz + wy],
        [xy + wz, 1.0 - xx - zz, yz - wx],
        [xz - wy, yz + wx, 1.0 - xx - yy],
    ]
}

/// `Q diag(l) Q^T` for the rotation `q`, and its eigenpairs by construction (`l` sorted).
fn planted(q: [f64; 4], l: V3) -> (M, Truth) {
    let r = rotation(q);
    let a = array::from_fn(|i| {
        array::from_fn(|j| (0..3).fold(0.0, |s, k| s + r[i][k] * l[k] * r[j][k]))
    });
    let mut order = [0, 1, 2];
    order.sort_by(|&i, &j| l[i].total_cmp(&l[j]));
    (
        a,
        Truth {
            lam: order.map(|k| l[k]),
            vec: order.map(|k| col(&r, k)),
        },
    )
}

/// A planted matrix of the strata of the header: `(what, matrix, truth)`.
fn planted_case() -> impl Strategy<Value = (std::string::String, M, Truth)> {
    let parts = (
        prop::array::uniform4(-1.0..1.0f64),
        0..5usize,
        0..=12i32,
        -6..=6i32,
        prop::array::uniform3(-1.0..1.0f64),
        any::<bool>(),
    );
    parts
        .prop_filter("a rotation", |p| {
            p.0.iter().map(|x| x * x).sum::<f64>() > 0.05
        })
        .prop_map(|(q, kind, k, e, r, neg)| {
            let g = 10f64.powi(-k);
            let s = 2f64.powi(e) * if neg { -1.0 } else { 1.0 };
            let (name, l) = match kind {
                0 => ("random", r),
                1 => ("bottom", [1.0, 1.0 + g, 3.0]),
                2 => ("top", [0.5, 2.0, 2.0 + 2.0 * g]),
                3 => ("rank1", [0.0, 0.0, 1.0]),
                _ => ("near-triple", [1.0, 1.0 + g, 1.0 + 2.0 * g]),
            };
            let (a, t) = planted(q, l.map(|x| x * s));
            (std::format!("{name} k {k} e {e} neg {neg}"), a, t)
        })
}

