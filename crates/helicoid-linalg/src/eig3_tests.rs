/// A matrix by rows, as `f64`.
type M = [[f64; 3]; 3];
type V3 = [f64; 3];

const K: f64 = 4.0;
const SLACK: f64 = 24.0;

/// The eigenpairs a decomposition is compared with: `vec[k]` is a unit eigenvector of `lam[k]`,
/// `lam` ascending.
#[derive(Debug)]
struct Truth {
    lam: V3,
    vec: [V3; 3],
}

/// The worst `value / bound` of each recorded bound.
#[derive(Clone, Copy, Default)]
struct Worst([f64; 3]);

fn dot(x: V3, y: V3) -> f64 {
    x[0] * y[0] + x[1] * y[1] + x[2] * y[2]
}

fn cross(x: V3, y: V3) -> V3 {
    [
        x[1] * y[2] - x[2] * y[1],
        x[2] * y[0] - x[0] * y[2],
        x[0] * y[1] - x[1] * y[0],
    ]
}

fn norm(x: V3) -> f64 {
    dot(x, x).sqrt()
}

fn col(v: &M, c: usize) -> V3 {
    array::from_fn(|r| v[r][c])
}

fn apply(a: &M, x: V3) -> V3 {
    a.map(|row| dot(row, x))
}

/// `a` with every entry rounded to `S`.
fn round<S: Lane>(a: &M) -> M {
    a.map(|r| r.map(|x| S::make(x, [0.0; 2]).lane(0)))
}

fn lower<S: Lane>(a: &M) -> Mat3<S> {
    Mat3::from_rows(a.map(|r| Vector(r.map(|x| S::make(x, [0.0; 2])))))
}

/// `eig3` at `S` of `a`: the eigenvalues and the matrix of eigenvectors by rows (`v[r][c]`).
fn run<S: Lane>(a: &M) -> (V3, M) {
    let (l, v) = eig3(&lower::<S>(a));
    (
        l.0.map(|x| x.lane(0)),
        array::from_fn(|r| array::from_fn(|c| v.get(r, c).lane(0))),
    )
}

/// `max |V^T V - I|` and `|det V - 1|`.
fn frame(v: &M) -> (f64, f64) {
    let cols = [0, 1, 2].map(|c| col(v, c));
    let orth = (0..9)
        .map(|i| (dot(cols[i / 3], cols[i % 3]) - f64::from(u8::from(i / 3 == i % 3))).abs())
        .fold(0.0, f64::max);
    (orth, (dot(cols[0], cross(cols[1], cols[2])) - 1.0).abs())
}

fn residual(a: &M, l: f64, v: V3) -> f64 {
    let av = apply(a, v);
    norm([0, 1, 2].map(|i| av[i] - l * v[i]))
}

/// Checks `eig3` at `S` on `a` against `t`: the frame always, the recorded bounds of the header where
/// the model applies, and `ev` alone where the top pair is a tie (`res` and `ang` stay 0 there). `a`
/// is rounded to `S` first, so `t` is the truth of `a` to within the slack. Returns the worst
/// `value / bound` of `ev`, `res`, `ang`.
fn check<S: Lane>(what: &str, a: &M, t: &Truth) -> Worst {
    let (a, u) = (round::<S>(a), unit::<S>());
    let (l, v) = run::<S>(&a);
    let (orth, det) = frame(&v);
    assert!(
        orth <= 16.0 * u && det <= 16.0 * u,
        "{what}: orth {orth:e} det {det:e}"
    );
    let an = t.lam.iter().fold(0.0_f64, |m, x| m.max(x.abs()));
    let gaps = [t.lam[1] - t.lam[0], t.lam[2] - t.lam[1]];
    let mut w = Worst::default();
    if an == 0.0 {
        return w;
    }
    let tie = gaps[1] < 4.0 * u.sqrt() * an;
    let c = 1.0 + (an / gaps[0].min(gaps[1])).min(1.0 / u.sqrt());
    let bound = (K * c + SLACK) * u * an;
    for k in 0..3 {
        let vk = col(&v, k);
        let gap = (0..3)
            .filter(|&j| j != k)
            .map(|j| (t.lam[k] - t.lam[j]).abs())
            .fold(f64::INFINITY, f64::min)
            .max(u * an);
        let got = [
            (l[k] - t.lam[k]).abs() / bound,
            residual(&a, l[k], vk) / bound,
            norm(cross(vk, t.vec[k])) * gap / bound,
        ];
        for (i, (g, name)) in got.iter().zip(["ev", "res", "ang"]).enumerate() {
            if tie && i > 0 {
                continue;
            }
            assert!(
                *g <= 1.0,
                "{what} at {:?}: {name} {g} of its bound, l {l:?}",
                S::PRECISION
            );
            w.0[i] = w.0[i].max(*g);
        }
    }
    w
}

/// Prints each new largest `value / bound` of `ev`, `res`, `ang` and its case when `EIG3_REPORT`
/// is set.
#[allow(clippy::print_stdout)]
fn note(what: &str, w: Worst) {
    static SEEN: std::sync::Mutex<[f64; 3]> = std::sync::Mutex::new([0.0; 3]);
    if let (Some(_), Ok(mut seen)) = (std::env::var_os("EIG3_REPORT"), SEEN.lock()) {
        if (0..3).any(|k| w.0[k] > seen[k]) {
            *seen = array::from_fn(|k| seen[k].max(w.0[k]));
            std::println!(
                "{what}: max ev {:.3} res {:.3} ang {:.3}",
                seen[0],
                seen[1],
                seen[2]
            );
        }
    }
}

