/// Four sweeps converge and three do not (`0024` decision 3): the count is measured, not assumed.
/// A mutation of the rotation's pairing or of its coefficients fails this test first.
#[test]
fn four_sweeps_converge_and_three_do_not() {
    fn residual<S: Lane, const N: usize>(a: &M) -> f64 {
        let (_, _, v) = with_sweeps::<S, N>(&at::<S>(a));
        let rows = array::from_fn(|r| array::from_fn(|c| v.get(r, c).lane(0)));
        column_residual(&round::<S>(a), &rows)
    }
    fn worst<S: Lane, const N: usize>() -> f64 {
        MP.iter()
            .map(|(_, a, _, _, _)| residual::<S, N>(a))
            .filter(|x| x.is_finite())
            .fold(0.0, f64::max)
    }

    // Four sweeps converge on the fixture at every precision, and more do not help.
    let four = worst::<f64, 4>() / unit::<f64>();
    let eight = worst::<f64, 8>() / unit::<f64>();
    assert!(four <= FRAME, "four sweeps leave {four:.1} u");
    assert!(
        eight >= four / 4.0,
        "eight sweeps improve on four by more than 4x: {eight:.1} u against {four:.1} u"
    );
    assert!(worst::<f32, 4>() / unit::<f32>() <= FRAME);
    assert!(worst::<D, 4>() / unit::<D>() <= FRAME);

    // Three do not. A random matrix is the hard family, not the structured fixture: over 200000
    // of them three sweeps leave 31% above `100 u` and reach `1.15e11 u`, four leave none above
    // `100 u` and reach `6.1 u` (`0024` decision 3). This row is the worst of that search.
    let hard: M = [
        [
            0.9091536682513737,
            0.019406312989399543,
            -0.2795799153522003,
        ],
        [-0.03062952942492947, 0.9444324870405088, 0.8121749635817201],
        [0.3429963297127787, -0.3187257372576153, -0.3367623266840054],
    ];
    let (r3, r4) = (
        residual::<f64, 3>(&hard) / unit::<f64>(),
        residual::<f64, 4>(&hard) / unit::<f64>(),
    );
    assert!(r3 > 1e10, "three sweeps leave only {r3:.3e} u");
    assert!(r4 <= FRAME, "four sweeps leave {r4:.1} u");

    // And the tail over a seeded pool of random matrices, in the repository rather than in a
    // scratch harness: three sweeps fail on some, four on none.
    let mut r = lcg(20260930);
    let (mut over3, mut w4) = (0usize, 0.0f64);
    for _ in 0..2000 {
        let a: M = array::from_fn(|_| array::from_fn(|_| r()));
        if residual::<f64, 3>(&a) / unit::<f64>() > 100.0 {
            over3 += 1;
        }
        w4 = w4.max(residual::<f64, 4>(&a) / unit::<f64>());
    }
    assert!(over3 > 200, "only {over3} of 2000 need a fourth sweep");
    assert!(w4 <= FRAME, "four sweeps leave {w4:.1} u on the pool");
}

/// The rotation of the unnormalised quaternion `(w, x, y, z)`, by rows.
fn rotation([w, x, y, z]: [f64; 4]) -> M {
    let k = 2.0 / (w * w + x * x + y * y + z * z);
    [
        [
            1.0 - k * (y * y + z * z),
            k * (x * y - w * z),
            k * (x * z + w * y),
        ],
        [
            k * (x * y + w * z),
            1.0 - k * (x * x + z * z),
            k * (y * z - w * x),
        ],
        [
            k * (x * z - w * y),
            k * (y * z + w * x),
            1.0 - k * (x * x + y * y),
        ],
    ]
}

/// `U diag(sigma) V^T` and the decomposition it was built from. The planted values are a design,
/// not the truth: the product rounds, so the bounds are asserted against the planted spectrum
/// with the rounding of the product added to the singular value bound by the caller.
fn planted(q1: [f64; 4], sigma: V3, q2: [f64; 4]) -> (M, Truth) {
    let (u, v) = (rotation(q1), rotation(q2));
    let a = array::from_fn(|r| {
        array::from_fn(|c| (0..3).map(|k| u[r][k] * sigma[k] * v[c][k]).sum::<f64>())
    });
    (a, Truth { sigma, u, v })
}

fn quat() -> impl Strategy<Value = [f64; 4]> {
    prop::array::uniform4(-1.0f64..1.0).prop_filter("degenerate quaternion", |q| {
        q.iter().map(|x| x * x).sum::<f64>() > 1e-3
    })
}

fn planted_case() -> impl Strategy<Value = (std::string::String, M, Truth)> {
    let family = prop_oneof![
        // distinct, well separated
        (0.25f64..4.0, 0.25f64..4.0, 0.25f64..4.0).prop_map(|(a, b, c)| ("distinct", [a, b, c])),
        // graded
        (1u32..17).prop_map(|k| {
            let g = 10f64.powi(-(k as i32));
            ("graded", [1.0, g, g * g])
        }),
        // a close pair, at either end
        (1u32..16, any::<bool>()).prop_map(|(k, top)| {
            let d = 10f64.powi(-(k as i32));
            if top {
                ("pair-top", [1.0, 1.0 - d, 0.25])
            } else {
                ("pair-bottom", [1.0, 0.5, 0.5 - 0.5 * d])
            }
        }),
        // rank deficient
        (0u8..3).prop_map(|r| match r {
            0 => ("rank2", [1.0, 0.5, 0.0]),
            1 => ("rank1", [1.0, 0.0, 0.0]),
            _ => ("rank0", [0.0, 0.0, 0.0]),
        }),
        // isotropic, and a scale sweep
        (-40i32..40).prop_map(|e| ("scaled", [1.0, 1.0, 1.0].map(|x: f64| x * 2f64.powi(e)))),
    ];
    (quat(), family, quat(), any::<bool>()).prop_map(|(q1, (what, mut sigma), q2, reflect)| {
        // The convention of the output: descending in magnitude, and only `sigma_3` signed.
        sigma.sort_by(|a, b| {
            b.abs()
                .partial_cmp(&a.abs())
                .unwrap_or(core::cmp::Ordering::Equal)
        });
        if reflect {
            sigma[2] = -sigma[2];
        }
        let (a, t) = planted(q1, sigma, q2);
        (
            std::format!("{what}{}", if reflect { ":reflected" } else { "" }),
            a,
            t,
        )
    })
}

