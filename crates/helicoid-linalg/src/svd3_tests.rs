/// Whether every entry of `a` is a number of `S`.
fn fits<S: Lane>(a: &M) -> bool {
    let r = round::<S>(a);
    (0..9).all(|i| r[i / 3][i % 3].to_bits() == a[i / 3][i % 3].to_bits())
}

fn strata<S: Lane>() {
    let mut worst = Worst::default();
    for &(name, a, sigma, u, v) in MP {
        assert!(
            fits::<S>(&a),
            "{name}: the fixture is not exact at this width"
        );
        let w = check::<S>(name, &a, &Truth { sigma, u, v });
        note(name, w);
        worst = worst.join(w);
    }
    note("WORST", worst);
}

