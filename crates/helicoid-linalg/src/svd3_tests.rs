/// A matrix by rows, as `f64`.
type M = [[f64; 3]; 3];
type V3 = [f64; 3];
/// `(name, A by rows, sigma, U by rows, V by rows)`.
type Row = (&'static str, M, V3, M, M);

/// The recorded multiple of `u` for the singular values and the angles: 12 rotations accumulate
/// their roundings, so an isotropic matrix reaches 16. A fit, not a bar (module docs).
const K: f64 = 24.0;

/// The recorded multiple of `u` for orthogonality, `det` and the reconstruction, which do not
/// carry the `1/gap` of an angle.
const FRAME: f64 = 32.0;

/// The decomposition a result is compared with.
#[derive(Debug)]
struct Truth {
    sigma: V3,
    u: M,
    v: M,
}

/// The worst `value / bound` of each recorded bound: singular values, angles, reconstruction,
/// frame.
#[derive(Clone, Copy, Default)]
struct Worst([f64; 4]);

impl Worst {
    fn join(self, o: Self) -> Self {
        Self(array::from_fn(|i| self.0[i].max(o.0[i])))
    }
}

fn dot(x: V3, y: V3) -> f64 {
    x[0] * y[0] + x[1] * y[1] + x[2] * y[2]
}

fn cross(x: V3, y: V3) -> V3 {
    [
        x[1] * y[2] - x[2] * y[1],
        x[2] * y[0] - x[0] * y[2],
        x[0] * y[1] - x[1] * y[0],
    ]
}

fn norm(x: V3) -> f64 {
    dot(x, x).sqrt()
}

fn col(m: &M, c: usize) -> V3 {
    array::from_fn(|r| m[r][c])
}

/// `a` with every entry rounded to `S`.
fn round<S: Lane>(a: &M) -> M {
    a.map(|r| r.map(|x| S::make(x, [0.0; 2]).lane(0)))
}

fn at<S: Lane>(a: &M) -> Mat3<S> {
    Mat3::from_rows(a.map(|r| Vector(r.map(|x| S::make(x, [0.0; 2])))))
}

/// `svd3` at `S` of `a`, with `U` and `V` by rows.
fn run<S: Lane>(a: &M) -> (M, V3, M) {
    let (u, s, v) = svd3(&at::<S>(a));
    let rows = |m: &Mat3<S>| array::from_fn(|r| array::from_fn(|c| m.get(r, c).lane(0)));
    (rows(&u), s.0.map(|x| x.lane(0)), rows(&v))
}

/// `max |M^T M - I|` and `|det M - 1|`.
fn frame(m: &M) -> (f64, f64) {
    let c = |k| col(m, k);
    let orth = (0..3)
        .flat_map(|i| (0..3).map(move |j| (i, j)))
        .map(|(i, j)| (dot(c(i), c(j)) - if i == j { 1.0 } else { 0.0 }).abs())
        .fold(0.0, f64::max);
    (orth, (dot(c(0), cross(c(1), c(2))) - 1.0).abs())
}

/// `max |U diag(sigma) V^T - A|`.
fn reconstruction(a: &M, u: &M, s: V3, v: &M) -> f64 {
    (0..3)
        .flat_map(|r| (0..3).map(move |c| (r, c)))
        .map(|(r, c)| ((0..3).map(|k| u[r][k] * s[k] * v[c][k]).sum::<f64>() - a[r][c]).abs())
        .fold(0.0, f64::max)
}

/// `max_{j<k} |b_j . b_k| / |A|^2` for `B = A V`: how far from orthogonal the sweeps left the
/// columns. Relative to the matrix scale, not to the two column norms, since for a
/// rank-deficient matrix both short columns are rounding noise and their own ratio says nothing.
fn column_residual(a: &M, v: &M) -> f64 {
    let b: [V3; 3] = array::from_fn(|k| {
        let vk = col(v, k);
        array::from_fn(|r| dot(a[r], vk))
    });
    let scale = (0..3).map(|k| norm(b[k])).fold(0.0, f64::max);
    let off = [(0, 1), (0, 2), (1, 2)]
        .map(|(j, k)| dot(b[j], b[k]).abs())
        .into_iter()
        .fold(0.0, f64::max);
    if scale > 0.0 {
        off / (scale * scale)
    } else {
        off
    }
}

/// The sine of the angle between the lines of `x` and `y`: sign-free, since only the pair
/// `(u_k, v_k)` is determined, not each column's sign.
fn angle(x: V3, y: V3) -> f64 {
    norm(cross(x, y)).min(1.0)
}

/// Every recorded bound, as `value / bound`.
fn check<S: Lane>(what: &str, a: &M, t: &Truth) -> Worst {
    let (u, s, v) = run::<S>(a);
    let eps = unit::<S>();
    let scale = t.sigma[0].abs();
    let mut w = Worst::default();

    // The frame is orthonormal with det = +1 for every input, scale or none.
    for m in [&u, &v] {
        let (orth, det) = frame(m);
        w.0[3] = w.0[3].max(orth / (FRAME * eps)).max(det / (FRAME * eps));
    }

    // |sigma_1| >= |sigma_2| >= |sigma_3| is exact: the sort is a compare-exchange on the
    // computed norms, and only sigma_3 carries a sign.
    assert!(
        s[0] >= s[1] && s[1] >= s[2].abs(),
        "{what}: out of order {s:?}"
    );
    assert!(s[0] >= 0.0 && s[1] >= 0.0, "{what}: negative sigma {s:?}");

    if scale <= 0.0 {
        // The zero matrix: every singular value is zero and the frame is all that is left.
        assert!(
            s.iter().all(|x| *x == 0.0),
            "{what}: {s:?} for a zero input"
        );
        return w;
    }

    let floor = eps * scale;
    for (k, sk) in s.iter().enumerate() {
        w.0[0] = w.0[0].max((sk - t.sigma[k]).abs() / (K * eps * scale));
        let gap = (0..3)
            .filter(|j| *j != k)
            .map(|j| (t.sigma[k].abs() - t.sigma[j].abs()).abs())
            .fold(f64::INFINITY, f64::min)
            .max(floor);
        let bound = K * eps * scale / gap;
        for (got, want) in [(&u, &t.u), (&v, &t.v)] {
            w.0[1] = w.0[1].max(angle(col(got, k), col(want, k)) / bound);
        }
    }
    w.0[2] = reconstruction(a, &u, s, &v) / (FRAME * eps * scale);
    w
}

/// The worst `value / bound` any case has reached, so the recorded bounds in the module docs are
/// a measurement and not an assertion. Bits of a non-negative `f64`, which `fetch_max` orders.
static PEAK: std::sync::atomic::AtomicU64 = std::sync::atomic::AtomicU64::new(0);

/// Records `w` and prints it under `SVD3_REPORT` when it is a new worst.
#[allow(clippy::print_stdout)]
fn peak(what: &str, w: Worst) {
    let x = w.0.iter().fold(0.0f64, |m, v| m.max(*v));
    let prev = PEAK.fetch_max(x.to_bits(), std::sync::atomic::Ordering::Relaxed);
    if x.to_bits() > prev && std::env::var_os("SVD3_REPORT").is_some() {
        std::println!(
            "peak {x:.3} at {what:<22} sv {:.3} ang {:.3} rec {:.3} frame {:.3}",
            w.0[0],
            w.0[1],
            w.0[2],
            w.0[3]
        );
    }
}

#[allow(clippy::print_stdout)]
fn note(what: &str, w: Worst) {
    if std::env::var_os("SVD3_REPORT").is_some() {
        std::println!(
            "{what:<20} sv {:.3} ang {:.3} rec {:.3} frame {:.3}",
            w.0[0],
            w.0[1],
            w.0[2],
            w.0[3]
        );
    }
    for (i, name) in ["sigma", "angle", "reconstruction", "frame"]
        .iter()
        .enumerate()
    {
        assert!(
            w.0[i] <= 1.0,
            "{what}: {name} at {:.3} of its bound",
            w.0[i]
        );
    }
}

