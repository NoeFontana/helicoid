//! Tests of `svd3`: the strata of `docs/PHASE2.md` §6 against mpmath, planted spectra, the sweep
//! count, the constructed gauge, the value path of `Dual` and its derivative, two lanes, and the
//! limits, pinned.
//!
//! **Metrics**, in `f64` from the `S` output, `u` the unit roundoff, `|A| = sigma_1*` the spectral
//! norm: `orth = max |M^T M - I|` and `det = |det M - 1|` for `M = U, V`; the singular value error
//! `sv = |sigma_k - sigma_k*|`; the angle `ang_k = |v_k x v_k*|` of each column of `U` and `V`,
//! sign-free, because a column pair `(u_k, v_k)` is fixed only up to a simultaneous flip; the
//! reconstruction `rec = max |U diag(sigma) V^T - A|`; and the column residual
//! `off = max_{j<k} |b_j . b_k| / |A|^2` of `B = A V`, which is what the sweeps drive to zero.
//!
//! **The recorded bounds** are `sv <= K u |A|`, `ang_k <= K u |A| / gap_k` with `gap_k` the
//! distance from `|sigma_k*|` to the nearest other singular value in magnitude (floored at
//! `u |A|`, where the bound is vacuous — at a tie the individual columns are not determined),
//! and `rec, orth, det <= FRAME u` (times `|A|` for `rec`). `K = 24`, `FRAME = 32`. They are a
//! fit to the measurements below, **not the bars of `PHASE2.md` §6**, which name no constant:
//! worst `value / bound` 0.32 over the fixture and 0.67 over 10^6 planted cases (seed 1).
//!
//! **Measured** worst over the fixture, `f64` then `f32` (`Dual<f64, 2>` equals `f64` to the bit):
//! `sv` 6.0 and 7.6 `u |A|`, `ang` 2.5 and 1.7 `u |A| / gap`, `rec` 5.0 and 9.5 `u |A|`, `orth`
//! and `det` 6.0 and 5.5 `u`. The planted families reach `sv` 16 `u |A|` on an isotropic spectrum,
//! which is the 12 rotations' accumulated rounding and is why `K` is 24 and not 8.
//!
//! **Orthonormality and `det = +1` hold to `FRAME u` inside the documented magnitude range; only
//! finiteness holds outside it.** There a Gram entry overflows or a column norm goes subnormal,
//! the rotation that would have separated two nearly parallel columns is skipped, and the
//! projection that builds the frame's second column cancels: the orthogonality of `U` reaches
//! about `sqrt(u)` (`outside_the_magnitude_range_the_frame_is_only_finite`). `in_range` is the
//! predicate, per column and at `S`'s own precision.
//!
//! **The singular values are accurate in `u |A|`, not relatively** — except on the column-graded
//! family `A = B diag(d)`, where they come out to 1.8 `u sigma_k` relatively down to
//! `sigma_3 / sigma_1 = 1e-32` (`col_graded_singular_values_are_relatively_accurate`). That
//! family is why `0024` chose the one-sided form: forming `A^T A` costs the right singular vectors
//! of a small close pair a factor `sigma_1 / sigma_2` (`1.5e-3` rad against `1.8e-9` at
//! `sigma_1 / sigma_2 = 1e6`, measured in `0024` *Context*).
//!
//! **The sweep count is measured here, not in a scratch harness**
//! (`four_sweeps_converge_and_three_do_not`): over 200000 random matrices three sweeps leave 31%
//! of them above `100 u` of column residual and reach `1.15e11 u`, four leave none above `100 u`
//! and reach `6.1 u`. The committed test pins the worst row of that search and a seeded pool.
//!
//! `MP` is the fixture: **every entry is exactly representable in binary32**, so `f32` and `f64`
//! decompose the same matrix; the singular values and singular vectors are `mp.svd_r` at 120
//! digits rounded to binary64, put in §6's signed convention (`det U = det V = +1`, the reflection
//! in `sigma_3`). Strata: `random`, `graded-1e-k` (`sigma = 1, 10^-k, 10^-2k`), `col-graded-1e-k`,
//! `small-pair-1e-k` (`sigma = 1, s, s(1 + 1e-4)`), `isotropic`, `tie`, `tie-top`, `rank2`,
//! `rank1`, `rotation`, `reflection`, `scaled-2e{+-k}`, `parallel`, and the fixed cases
//! `identity`, `neg-identity`, `diag-mixed`, `diag-signed`, `int-nonsingular`, `int-singular`,
//! `one-entry` and `zero`: 21 families over 82 rows. The generator is not committed. The planted proptest is run at 10^6 cases with
//!
//! ```text
//! SVD3_REPORT=1 PROPTEST_CASES=1000000 PROPTEST_RNG_SEED=1 cargo nextest run --release \
//!     --no-capture -p helicoid-linalg svd3_tests
//! ```

